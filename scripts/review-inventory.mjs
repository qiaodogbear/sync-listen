import fs from "node:fs/promises";
import path from "node:path";
const root = path.resolve(import.meta.dirname, "..");
const modules = ["android-app", "backend", "shared", "desktop", "protocol"];
const files = [];
async function visit(directory) {
  for (const item of await fs.readdir(directory, { withFileTypes: true })) {
    if (["build", "node_modules", ".gradle", ".kotlin", "dist"].includes(item.name)) continue;
    const filename = path.join(directory, item.name);
    if (item.isDirectory()) await visit(filename);
    else if (/\.(kt|ts)$/.test(item.name)) {
      const source = await fs.readFile(filename, "utf8");
      const relative = path.relative(root, filename).replaceAll("\\", "/");
      files.push({ path: relative, module: relative.split("/")[0],
        kind: /\/test\//.test(relative) ? "test" : "source",
        lines: source.trimEnd().split(/\r?\n/).length });
    }
  }
}
for (const name of modules) await visit(path.join(root, name));
files.sort((a,b) => a.path.localeCompare(b.path));
const statistics = modules.map(module => {
  const list = files.filter(f => f.module === module);
  return { module, sourceFiles: list.filter(f => f.kind === "source").length,
    testFiles: list.filter(f => f.kind === "test").length,
    lines: list.reduce((n,f) => n + f.lines, 0) };
});
await fs.mkdir(path.join(root, "docs/review"), { recursive: true });
await fs.writeFile(path.join(root, "docs/review/inventory.json"), JSON.stringify({ date:"2026-09-16", statistics, files }, null, 2) + "\n");
const rows = files.map(f => "| " + f.path + " | " + f.kind + " | " + f.lines + " |");
await fs.writeFile(path.join(root, "docs/review/inventory.md"),
  "# Source Inventory\n\nGenerated by scripts/review-inventory.mjs. Includes Kotlin and TypeScript source and tests; excludes generated build output. Line counts are physical lines, not test coverage.\n\n| File | Kind | Lines |\n|---|---|---:|\n" + rows.join("\n") + "\n");
console.log(JSON.stringify(statistics));
